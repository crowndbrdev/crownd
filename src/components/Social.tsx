function lookup(url: string) {
  const host = new URL(url).hostname.replace(/^www\./, "");
  return ICONS[host] ?? { name: host, svg: null };
}

/**
 * Official profiles as icon buttons (same list as Organization.sameAs). rel="me" makes the
 * site ↔ profile relationship two-way, which search engines use to merge the brand entity.
 * The network name stays as aria-label/title for screen readers and hover.
 */
export function SocialLinks({ className = "" }: { className?: string }) {
  if (!SAME_AS.length) return null;
  return (
    <ul className={`flex flex-wrap gap-2 ${className}`} aria-label="Crownd social">
      {SAME_AS.map((url) => {
        const { name, svg } = lookup(url);
        return (
          <li key={url}>
            <a
              href={url}
              rel="me noopener"
              target="_blank"
              aria-label={name}
              title={name}
              className="grid h-9 w-9 place-items-center rounded-full border border-line-strong text-ink-2 transition hover:border-ink hover:text-ink"
            >
              {svg ? (
                <svg viewBox="0 0 24 24" width="16" height="16" fill="currentColor" aria-hidden="true">{svg}</svg>
              ) : (
                <span className="text-[10px] font-semibold">{name.slice(0, 2)}</span>
              )}
            </a>
          </li>
        );
      })}
    </ul>
  );
}
